/** Normalise un mot : minuscules, sans accents, sans doubles consonnes */
export function normalizePhonetic(word: string): string {
    return word
        .toLowerCase()
        .normalize('NFD').replace(/[\u0300-\u036f]/g, '')  // strip accents
        .replace(/(.)\1+/g, '$1')                          // double→single
        .replace(/ph/g, 'f')                               // ph→f
        .replace(/th/g, 't')                                // th→t
        .replace(/y/g, 'i');                                // y→i
}

